import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import puppeteer from 'puppeteer-core';
const url = process.env.SHOTS_URL ?? 'http://localhost:5185';
mkdirSync('shots-out/ride-modes', { recursive: true });
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--mute-audio'], defaultViewport: { width: 1440, height: 900 } });
const errors = [], requests = [];
try {
  const page = await browser.newPage();
  page.on('pageerror', e => errors.push(e.message));
  await page.setRequestInterception(true);
  page.on('request', req => {
    const path = new URL(req.url()).pathname;
    const json = body => req.respond({ contentType: 'application/json', body: JSON.stringify(body) });
    if (path === '/api/health') return void json({ configured: false });
    if (path === '/api/driver/health') return void json({ configured: true, voice: 'off' });
    if (path === '/api/driver/cast') return void json(null);
    if (path === '/api/driver/line') {
      const q = JSON.parse(req.postData()); requests.push(q);
      return void json({ text: q.ride?.phone ? `${q.ride.phone.caller}, put the kettle on. I have an opinion about this traffic.` : q.ride?.quote ? 'Thirty minutes, mate. I know every shortcut in this town.' : 'Morning. Where are we off to then, mate?', mood: 'grumble', gesture: 'hand', audio: null, model: 'test', engine: 'test', wordsMs: 1, voiceMs: 0 });
    }
    if (path.startsWith('/api/driver/') || path === '/api/drive') return void json({});
    void req.continue();
  });
  await page.goto(url, { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('.landing-editions');
  assert.equal(await page.$eval('.landing-editions button:first-child', e=>e.getAttribute('aria-pressed')), 'true');
  await page.screenshot({path:'shots-out/ride-modes/landing-france.png'});
  await Promise.all([page.waitForNavigation({waitUntil:'domcontentloaded'}), page.click('.landing-editions button:last-child')]);
  await page.waitForSelector('.landing-editions');
  assert.equal(await page.$eval('.landing-editions button:last-child', e=>e.getAttribute('aria-pressed')), 'true');
  assert.deepEqual(await page.$$eval('.sign strong', els=>els.map(e=>e.textContent)), ['London']);
  assert.equal(await page.$eval('.taximeter-unit', e=>e.textContent), '£');
  await page.setViewport({width:390,height:844});
  await page.screenshot({path:'shots-out/ride-modes/landing-london-mobile.png'});
  assert.ok(await page.$eval('.landing-editions', e=>e.getBoundingClientRect().right<=innerWidth && e.getBoundingClientRect().left>=0));
  await page.focus('.landing-editions button:first-child');
  await Promise.all([page.waitForNavigation({waitUntil:'domcontentloaded'}), page.keyboard.press('Enter')]);
  await page.waitForSelector('.landing-editions');
  assert.equal(await page.$eval('.landing-editions button:first-child', e=>e.getAttribute('aria-pressed')), 'true');
  assert.ok(await page.$$eval('.sign strong', els=>els.some(e=>e.textContent==='Cassis')));
  await Promise.all([page.waitForNavigation({waitUntil:'domcontentloaded'}), page.click('.landing-editions button:last-child')]);
  await page.waitForSelector('.landing-editions');
  await page.setViewport({width:1440,height:900});
  await page.click('.sign');
  assert.ok(!new URL(page.url()).searchParams.has('start'));
  console.log('PASS landing editions switch both ways, keyboard, mobile, and London start');
  await page.waitForFunction(async () => { const {get}=await import('/src/store.ts'); return get().status==='ready' && get().built===1 && window.jevRoads?.chatter.persona.name === 'Terry'; }, { timeout: 60000 });
  console.log('PASS London auto-load, preloaded cabbie, all nine scenery tiles');
  const state = await page.evaluate(async () => { const {get}=await import('/src/store.ts'); const g=window.jevRoads.game; return { place:get().place, provider:get().mapProvider, world:get().worldMode, name:g.chatter.persona.name, cabinZ:g.view.cockpit.group.scale.z, roads:g.frame.net.lanes.length }; });
  assert.equal(state.provider, 'google'); assert.equal(state.world,'reconstructed'); assert.equal(state.cabinZ,-1); assert.ok(state.place.includes('London')); assert.ok(state.roads>100);
  await page.evaluate(async () => { const g=window.jevRoads.game; g.setSky('midday','clear'); g.startRide(g.ride.destinations()[0].label); const {get,set}=await import('/src/store.ts'); set({gps:false,quoteSeen:true}); });
  await page.waitForFunction(() => window.jevRoads.game.ride.phase === 'riding');
  await page.evaluate(() => window.jevRoads.game.chatter.stop());
  console.log('Starting call',await page.evaluate(()=>window.jevRoads.game.ride.view().phone));
  await page.click('.gear');
  await page.screenshot({path:'shots-out/ride-modes/london-settings.png'});
  await page.click('[data-action="ring-phone"]');
  await page.waitForSelector('.driver-phone.is-ringing');
  assert.ok(await page.$eval('.phone-interrupt', e=>e.textContent.includes('−8 sympathy')));
  await page.screenshot({path:'shots-out/ride-modes/london-ringing.png'});
  await page.waitForSelector('.driver-phone.is-talking', {timeout:15000});
  await page.waitForFunction(()=>window.jevRoads.game.chatter.talk.speaking);
  assert.ok(requests.some(q=>q.ride?.phone && q.persona.locale==='en-GB' && !q.offer));
  await page.screenshot({path:'shots-out/ride-modes/london-call.png'});
  const before=await page.evaluate(()=>window.jevRoads.game.ride.sympathie);
  await page.click('.phone-interrupt');
  await page.waitForSelector('.driver-phone',{hidden:true});
  const after=await page.evaluate(()=>({points:window.jevRoads.game.ride.sympathie,verdict:window.jevRoads.game.ride.view().verdict}));
  assert.ok(Math.abs(before-after.points-8)<0.5); assert.equal(after.verdict.points,-8);
  writeFileSync('shots-out/ride-modes/phone-query.json',JSON.stringify(requests.find(q=>q.ride?.phone)));
  console.log('PASS animated ring, connected caller dialogue, Interrupt -8 points');
  await page.evaluate(()=>window.jevRoads.game.ride.ringPhone());
  await page.waitForSelector('.driver-phone');
  await page.setViewport({width:390,height:844});
  await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}]);
  await page.screenshot({path:'shots-out/ride-modes/london-mobile.png'});
  assert.ok(await page.$eval('.driver-phone',e=>e.getBoundingClientRect().right<=innerWidth && e.getBoundingClientRect().left>=0));
  assert.equal(await page.$eval('.phone-handset',e=>getComputedStyle(e).animationName),'none');
  await page.click('.phone-interrupt');
  console.log('PASS mobile call controls and reduced motion');
  await page.setViewport({width:1440,height:900});
  await page.goto(`${url}/?edition=fr&scene=reconstructed`,{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>Boolean(window.jevRoads));
  await page.evaluate(()=>window.jevRoads.open({name:'Preignac',lat:44.5854,lon:-0.2962}));
  await page.waitForFunction(async()=>{const {get}=await import('/src/store.ts');return get().built===1;},{timeout:60000});
  await page.evaluate(async()=>{const g=window.jevRoads.game;g.startRide(g.ride.destinations()[0].label);const {set}=await import('/src/store.ts');set({gps:false,quoteSeen:true});g.setMode('above');});
  await new Promise(r=>setTimeout(r,2200));
  await page.screenshot({path:'shots-out/ride-modes/preignac-clearance.png'});
  console.log('PASS Preignac reconstructed scene renders completely');
  assert.deepEqual(errors,[]);
  console.log('PASS no page errors');
} finally { await browser.close(); }
